#!/usr/bin/env python3
"""Lightweight host traffic monitor for the Unified Security dashboard.

The upstream project expects a TShark-based monitor on port 5556.  TShark is
not available on this host, so this monitor sources the same information from
the kernel:

* ``/proc/net/dev`` for a 30 second, per-second throughput series (all physical
  interfaces, which includes traffic generated by Docker containers).
* ``ss -tinHe`` for live TCP/UDP sockets, byte/packet counters and socket inode.

It intentionally has no packet-capture dependency and runs comfortably as an
unprivileged user.  Endpoints match what the traffic-analyzer already calls.
"""

from __future__ import annotations

import hashlib
import ipaddress
import json
import os
import re
import subprocess
import threading
import time
from collections import deque
from datetime import datetime, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from urllib.parse import parse_qs, urlparse

WINDOW_SECONDS = 30
MAX_SAMPLES = 180
IFACE_RE = re.compile(r"^\s*([^:]+):\s*(.*)$")
STATS_RE = {
    "bytes_sent": re.compile(r"bytes_sent:(\d+)"),
    "bytes_received": re.compile(r"bytes_received:(\d+)"),
    "segs_out": re.compile(r"segs_out:(\d+)"),
    "segs_in": re.compile(r"segs_in:(\d+)"),
}


def _is_physical_iface(name: str) -> bool:
    """Return True for interfaces whose /proc/net/dev counters we aggregate."""
    if not name or name == "lo":
        return False
    prefixes = (
        "docker", "br-", "veth", "virbr", "tailscale", "zt", "wg",
        "tun", "tap", "l4tbr", "dummy",
    )
    return not name.startswith(prefixes)


_INFRA_NETWORKS = tuple(
    ipaddress.ip_network(value)
    for value in ("172.17.0.0/16", "172.18.0.0/16", "192.168.250.0/24",
                  "192.168.251.0/24", "192.168.55.0/24")
)


def _normalize_ip(value: str) -> str:
    """Return a canonical IP address, or an empty string for junk endpoints."""
    text = str(value or "").strip().strip("[]")
    if "%" in text:
        text = text.split("%", 1)[0]
    try:
        address = ipaddress.ip_address(text)
    except ValueError:
        return ""
    if address.is_unspecified or address.is_multicast:
        return ""
    return str(address)


def _is_infra_ip(value: str) -> bool:
    text = _normalize_ip(value)
    if not text:
        return True
    address = ipaddress.ip_address(text)
    if address.version != 4:
        return True
    if address.is_loopback or address.is_link_local:
        return True
    return any(address in network for network in _INFRA_NETWORKS)


def read_interface_counters() -> dict:
    counters = {}
    try:
        with open("/proc/net/dev", "r", encoding="utf-8") as handle:
            for line in handle:
                match = IFACE_RE.match(line)
                if not match:
                    continue
                name = match.group(1).strip()
                fields = match.group(2).split()
                if len(fields) < 16 or not _is_physical_iface(name):
                    continue
                counters[name] = {
                    "rx_bytes": int(fields[0]),
                    "tx_bytes": int(fields[8]),
                    "rx_packets": int(fields[1]),
                    "tx_packets": int(fields[9]),
                }
    except OSError:
        pass
    return counters


def _split_endpoint(endpoint: str) -> tuple[str, int | None]:
    endpoint = (endpoint or "").strip()
    if endpoint.startswith("["):
        host, _, port = endpoint[1:].rpartition("]:")
    else:
        host, _, port = endpoint.rpartition(":")
    try:
        port_number = int(port)
    except (TypeError, ValueError):
        port_number = None
    return host or endpoint, port_number


def _is_loopback(host: str) -> bool:
    host = (host or "").split("%", 1)[0]
    return host in ("127.0.0.1", "::1", "::", "*") or host.startswith("127.")


def _flow_id(protocol: str, src: str, sport, dst: str, dport, inode: str) -> str:
    raw = f"{protocol}|{src}|{sport}|{dst}|{dport}|{inode}"
    return "flow_" + hashlib.sha1(raw.encode("utf-8", "replace")).hexdigest()[:16]


def _socket_inode(line: str) -> str:
    # ss -e prints "ino:12345" on the detail line.
    match = re.search(r"\bino:(\d+)", line)
    return match.group(1) if match else ""


def parse_ss_output(output: str, protocol: str, now: datetime) -> list[dict]:
    flows = []
    current = None

    def flush():
        nonlocal current
        if not current:
            return
        stats = current["stats"]
        src, sport = current["src"]
        dst, dport = current["dst"]
        if _is_loopback(src) or _is_loopback(dst):
            current = None
            return
        inode = current["inode"]
        flows.append({
            "flow_id": _flow_id(protocol, src, sport, dst, dport, inode),
            "src_ip": src,
            "src_port": sport,
            "dest_ip": dst,
            "dest_port": dport,
            "protocol": protocol,
            "state": current["state"],
            "bytes_sent": int(stats.get("bytes_sent", 0)),
            "bytes_recv": int(stats.get("bytes_received", 0)),
            "packets_sent": int(stats.get("segs_out", 0)),
            "packets_recv": int(stats.get("segs_in", 0)),
            "inode": inode,
            "timestamp": now.isoformat() + "Z",
        })
        current = None

    for raw_line in output.splitlines():
        if not raw_line.strip():
            continue
        if raw_line[0].isspace():
            if current is None:
                continue
            for key, pattern in STATS_RE.items():
                match = pattern.search(raw_line)
                if match:
                    current["stats"][key] = match.group(1)
            if not current["inode"]:
                current["inode"] = _socket_inode(raw_line)
            continue

        parts = raw_line.split()
        if len(parts) < 5:
            continue
        # TCP: [State] Recv-Q Send-Q Local Peer [...].  `ss -H state
        # established` omits the State column, while a plain `ss -t`
        # includes it; support both layouts instead of assuming one.
        # UDP: State Recv-Q Send-Q Local Peer, where only established
        # sockets are flows (UNCONN entries are listeners, not traffic).
        if protocol == "tcp":
            state = "established"
            if parts[0].upper() in ("ESTAB", "ESTABLISHED"):
                local_idx, peer_idx = 3, 4
            elif parts[0].isdigit():
                local_idx, peer_idx = 2, 3
            else:
                continue
        else:
            state_name = parts[0].upper() if parts[0].isalpha() else "ESTAB"
            if state_name not in ("ESTAB", "ESTABLISHED"):
                continue
            state = "udp"
            local_idx, peer_idx = 3, 4
        if len(parts) <= peer_idx:
            continue
        local, peer = parts[local_idx], parts[peer_idx]
        if peer in ("*:*", "0.0.0.0:*", "[::]:*"):
            continue
        inode = _socket_inode(raw_line)
        flush()
        src_host, src_port = _split_endpoint(local)
        dst_host, dst_port = _split_endpoint(peer)
        src_host = _normalize_ip(src_host)
        dst_host = _normalize_ip(dst_host)
        if not src_host or not dst_host:
            current = None
            continue
        current = {
            "src": (src_host, src_port),
            "dst": (dst_host, dst_port),
            "state": state,
            "inode": inode,
            "stats": {},
        }
    flush()
    return flows


def read_connections() -> list[dict]:
    now = datetime.now(timezone.utc).replace(tzinfo=None)
    flows = []
    commands = [
        ("tcp", ["ss", "-tinHe", "state", "established"]),
        ("udp", ["ss", "-uanHe"]),
    ]
    for protocol, command in commands:
        try:
            result = subprocess.run(
                command, capture_output=True, text=True, timeout=8, check=False
            )
            if result.stdout:
                flows.extend(parse_ss_output(result.stdout, protocol, now))
        except (OSError, subprocess.SubprocessError):
            continue

    # Best talkers first, then most recently active.
    flows.sort(key=lambda f: (f["bytes_sent"] + f["bytes_recv"]), reverse=True)
    return flows[:500]


class TrafficSampler:
    def __init__(self):
        self.samples = deque(maxlen=MAX_SAMPLES)
        self.connections = []
        self.connections_updated = 0.0
        self.lock = threading.Lock()
        self.running = True

    def sample_counters(self):
        while self.running:
            counters = read_interface_counters()
            rx = sum(item["rx_bytes"] for item in counters.values())
            tx = sum(item["tx_bytes"] for item in counters.values())
            with self.lock:
                self.samples.append({
                    "t": time.time(),
                    "rx": rx,
                    "tx": tx,
                    "interfaces": sorted(counters),
                })
            time.sleep(1)

    def sample_connections(self):
        while self.running:
            try:
                flows = read_connections()
                with self.lock:
                    self.connections = flows
                    self.connections_updated = time.time()
            except Exception:
                pass
            time.sleep(2)

    def start(self):
        threading.Thread(target=self.sample_counters, daemon=True).start()
        threading.Thread(target=self.sample_connections, daemon=True).start()

    def series(self, window: int = WINDOW_SECONDS) -> dict:
        window = max(10, min(int(window or WINDOW_SECONDS), 120))
        with self.lock:
            samples = list(self.samples)
            connections = list(self.connections)
            connections_updated = self.connections_updated

        now = time.time()
        start = now - window
        # Build one rate value per second from adjacent counter samples.  The
        # final bucket is extended to "now" so the chart always ends live.
        rates = {}
        for previous, current in zip(samples, samples[1:]):
            elapsed = current["t"] - previous["t"]
            if elapsed <= 0 or elapsed > 5:
                continue
            bucket = int(current["t"])
            rx_rate = max(0.0, (current["rx"] - previous["rx"]) / elapsed)
            tx_rate = max(0.0, (current["tx"] - previous["tx"]) / elapsed)
            if bucket in rates:
                rates[bucket]["rx_bps"] += rx_rate * 8
                rates[bucket]["tx_bps"] += tx_rate * 8
            else:
                rates[bucket] = {"rx_bps": rx_rate * 8, "tx_bps": tx_rate * 8}

        points = []
        for second in range(int(start), int(now) + 1):
            value = rates.get(second, {"rx_bps": 0.0, "tx_bps": 0.0})
            points.append({
                "t": second,
                "rx_bps": round(value["rx_bps"], 2),
                "tx_bps": round(value["tx_bps"], 2),
            })

        window_samples = [s for s in samples if s["t"] >= start - 2]
        if window_samples:
            first, last = window_samples[0], window_samples[-1]
            span = max(0.0, last["t"] - first["t"])
            rx_bytes = max(0, last["rx"] - first["rx"])
            tx_bytes = max(0, last["tx"] - first["tx"])
            span = span or 1.0
        else:
            span, rx_bytes, tx_bytes = 0.0, 0, 0

        selected = [p for p in points if p["t"] >= math_floor(start)]
        peak_rx = max((p["rx_bps"] for p in selected), default=0.0)
        peak_tx = max((p["tx_bps"] for p in selected), default=0.0)
        interfaces = samples[-1]["interfaces"] if samples else []

        return {
            "status": "success",
            "window_seconds": window,
            "points": points,
            "summary": {
                "rx_bytes": rx_bytes,
                "tx_bytes": tx_bytes,
                "total_bytes": rx_bytes + tx_bytes,
                "rx_bps": points[-1]["rx_bps"] if points else 0.0,
                "tx_bps": points[-1]["tx_bps"] if points else 0.0,
                "peak_rx_bps": round(peak_rx, 2),
                "peak_tx_bps": round(peak_tx, 2),
                "sample_span_seconds": round(span, 1),
            },
            "active_connections": len(connections),
            "interfaces": interfaces,
            "sample_age_seconds": round(now - samples[-1]["t"], 1) if samples else None,
            "connections_age_seconds": round(now - connections_updated, 1) if connections_updated else None,
            "generated_at": int(now),
        }


def math_floor(value: float) -> int:
    return int(value // 1)


sampler = TrafficSampler()
sampler.start()


def _health_payload():
    with sampler.lock:
        sample_count = len(sampler.samples)
        connection_count = len(sampler.connections)
    return {
        "status": "healthy",
        "service": "host-traffic-monitor",
        "source": "procfs+ss",
        "samples": sample_count,
        "active_connections": connection_count,
        "timestamp": datetime.now(timezone.utc).isoformat(),
    }


def _connections_payload():
    with sampler.lock:
        flows = list(sampler.connections)
        updated = sampler.connections_updated
    return {
        "status": "success",
        "connections": flows,
        "count": len(flows),
        "updated_at": int(updated) if updated else None,
    }


def _dhcp_payload():
    """Neighbour table fallback for dashboards that expect DHCP fingerprints."""
    devices = []
    try:
        result = subprocess.run(
            ["ip", "-j", "neigh", "show"], capture_output=True, text=True, timeout=5
        )
        for entry in json.loads(result.stdout or "[]"):
            ip = entry.get("dst")
            mac = entry.get("lladdr")
            dev = entry.get("dev") or ""
            # ``ip neigh`` includes Docker bridges and the L4T USB bridge.
            # They are host infrastructure, not LAN devices, and must never
            # inflate the dashboard's previous-device list.
            if not _is_physical_iface(dev):
                continue
            if not ip or _is_infra_ip(ip) or not mac:
                continue
            devices.append({
                "ip_address": ip,
                "mac_address": mac,
                "interface": dev,
                "state": entry.get("state"),
                "hostname": None,
                "source": "neighbour-table",
            })
    except Exception:
        pass
    return {"status": "success", "devices": devices, "count": len(devices)}


class TrafficRequestHandler(BaseHTTPRequestHandler):
    server_version = "HostTrafficMonitor/1.0"

    def _send(self, payload, status=200):
        body = json.dumps(payload, separators=(",", ":")).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):  # noqa: N802 - BaseHTTPRequestHandler API
        parsed = urlparse(self.path)
        if parsed.path == "/health":
            self._send(_health_payload())
        elif parsed.path == "/series":
            window = parse_qs(parsed.query).get("window", [str(WINDOW_SECONDS)])[0]
            try:
                window_number = int(window)
            except ValueError:
                window_number = WINDOW_SECONDS
            self._send(sampler.series(window_number))
        elif parsed.path == "/connections":
            self._send(_connections_payload())
        elif parsed.path == "/dhcp/devices":
            self._send(_dhcp_payload())
        else:
            self._send({"error": "not found"}, status=404)

    def do_POST(self):  # noqa: N802 - BaseHTTPRequestHandler API
        if self.path in ("/restart-capture", "/start-capture", "/stop-capture"):
            self._send({"status": "success", "message": "Kernel sampling is always active"})
        else:
            self._send({"error": "not found"}, status=404)

    def log_message(self, format, *args):  # noqa: A002 - base class signature
        return


if __name__ == "__main__":
    port = int(os.environ.get("TRAFFIC_MONITOR_PORT", "5556"))
    ThreadingHTTPServer(("0.0.0.0", port), TrafficRequestHandler).serve_forever()
